"""
Executor component.

The Executor is responsible for executing
an investigation plan generated by the Planner.
"""

from collections.abc import Callable

from centaurus.executor.execution import (
    ExecutionFailure,
    ExecutionPlan,
    ExecutionTask,
)
from centaurus.exceptions import PluginExecutionError
from centaurus.plugin_manager.plugin_manager import PluginManager


TaskProgressCallback = Callable[
    [str, int, int, ExecutionTask, ExecutionFailure | None],
    None,
]


class Executor:
    """
    Executor component.

    The Executor coordinates the execution of the tasks contained
    in an ExecutionPlan.

    It delegates plugin execution to the Plugin Manager.

    The Executor never:
    - creates execution plans;
    - modifies execution plans;
    - replans investigations;
    - discovers or loads plugins directly.
    """

    def __init__(
        self,
        plugin_manager: PluginManager,
        progress_callback: TaskProgressCallback | None = None,
    ) -> None:
        """
        Create a new Executor.

        The Plugin Manager is provided by the Core, which owns
        the lifecycle of the framework components.
        """

        self._plugin_manager = plugin_manager
        self._progress_callback = progress_callback

    # ==========================================================
    # Public interface
    # ==========================================================

    def execute(
        self,
        plan: ExecutionPlan,
    ) -> dict:
        """
        Execute all tasks contained in an execution plan.

        Isolated plugin failures are recorded and later planned tasks
        continue to execute sequentially. Framework failures outside
        the plugin boundary still propagate.

        Returns a structured execution result.
        """

        results = []
        failures: list[ExecutionFailure] = []

        task_total = len(plan.tasks)

        for task_index, task in enumerate(
            plan.tasks,
            start=1,
        ):
            self._notify_progress(
                "started",
                task_index,
                task_total,
                task,
                None,
            )
            try:
                result = self._plugin_manager.execute(
                    task,
                )
            except PluginExecutionError as exc:
                failure = ExecutionFailure.from_exception(
                    task_index=task_index,
                    task=task,
                    exc=exc,
                )
                failures.append(failure)
                self._notify_progress(
                    "failed",
                    task_index,
                    task_total,
                    task,
                    failure,
                )
                continue

            results.append(result)
            self._notify_progress(
                "succeeded",
                task_index,
                task_total,
                task,
                None,
            )

        if failures and results:
            status = "partial"
        elif failures:
            status = "failed"
        else:
            status = "completed"

        return {
            "status": status,
            "results": results,
            "failures": failures,
        }

    def _notify_progress(
        self,
        state: str,
        task_index: int,
        task_total: int,
        task: ExecutionTask,
        failure: ExecutionFailure | None,
    ) -> None:
        """Return task-lifecycle facts through the callback owned by Core."""

        if self._progress_callback is None:
            return
        self._progress_callback(
            state,
            task_index,
            task_total,
            task,
            failure,
        )
